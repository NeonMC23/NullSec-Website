/**
 * NullSec — Account profile module
 * ------------------------------------------------------------------
 * Session-scoped account data (private, synced to Supabase). Data access goes
 * through ProfileRepository (source of truth = Supabase; in-memory session
 * cache while no backend is live). Never touches localStorage. Linked to the
 * account identity (identity_id must match Identity.get().id).
 *
 * M31: this is PRIVATE account data (not a public/social profile). The fields
 * username/avatar_seed are retained only because the Supabase `user_profiles`
 * table stores them; they are never exposed publicly and there is no
 * username/avatar UI.
 *
 * Schema (see docs/identity-schema.md §profile):
 *   {
 *     version: 1,
 *     identity_id: "<uuid>",
 *     username: "Anonymous",
 *     avatar_seed: "<random>",
 *     created_at: "<iso>",
 *     updated_at: "<iso>",
 *     recovery_created_at: "<iso>"   // set once when the recovery key is created
 *   }
 *
 * The recovery key itself is NEVER stored inside the profile — it lives
 * separately in sessionStorage via SessionStore (see recovery-key.js /
 * recovery-key.md). `recovery_created_at` merely records that a key has been issued.
 *
 * API:
 *   UserProfile.init()   — ensure a profile exists (create if missing)
 *   UserProfile.get()    — current profile (or null)
 *   UserProfile.create() — create + persist a new profile
 *   UserProfile.update(data) — merge allowed fields, bump updated_at
 *   UserProfile.clear()  — delete the account profile
 *   UserProfile.exists() — boolean
 */
(function () {
  'use strict';

  const SCHEMA_VERSION = 1;
  const DEFAULT_USERNAME = 'Anonymous';

  function now() {
    return new Date().toISOString();
  }

  /** Random alphanumeric seed used to derive a deterministic avatar. */
  function randomSeed() {
    const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
    let out = '';
    for (let i = 0; i < 12; i++) {
      out += chars[Math.floor(Math.random() * chars.length)];
    }
    return out;
  }

  /** Resolve the current local identity (creating it if absent). */
  function resolveIdentity() {
    if (!Identity.get()) Identity.init();
    return Identity.get();
  }

  /** Build a fresh profile bound to the given identity id. */
  function makeProfile(identityId) {
    const ts = now();
    return {
      version: SCHEMA_VERSION,
      identity_id: identityId,
      username: DEFAULT_USERNAME,
      avatar_seed: randomSeed(),
      created_at: ts,
      updated_at: ts,
      recovery_created_at: null
    };
  }

  /**
   * Ensure a recovery key exists for this profile, creating it exactly once.
   * Records `recovery_created_at` on the profile when a key is first issued.
   * The key is generated by RecoveryKey and stored separately in sessionStorage.
   * Returns the (possibly updated) stored profile.
   */
  function ensureRecovery() {
    let profile = ProfileRepository.get();
    const existing = RecoveryKey.get();
    if (!existing) {
      RecoveryKey.ensure();
      if (profile && !profile.recovery_created_at) {
        profile.recovery_created_at = now();
        ProfileRepository.save(profile);
      } else if (!profile) {
        profile = ProfileRepository.get();
        if (profile && !profile.recovery_created_at) {
          profile.recovery_created_at = now();
          ProfileRepository.save(profile);
        }
      }
    }
    return ProfileRepository.get();
  }

  /**
   * Ensure a profile exists; create one if missing or invalid/mismatched.
   * On first creation (or first init with no recovery key yet), generates a
   * recovery key exactly once.
   */
  function init() {
    let profile = exists() ? get() : create();
    profile = ensureRecovery() || profile;
    return profile;
  }

  /** Return the current profile, or null. */
  function get() {
    return ProfileRepository.get();
  }

  /** Create and persist a new profile bound to the current identity. */
  function create() {
    const identity = resolveIdentity();
    const profile = makeProfile(identity.id);
    ProfileRepository.save(profile);
    return ensureRecovery() || profile;
  }

  /**
   * Update profile fields (merge allowed fields). id, identity_id and
   * created_at are preserved; updated_at is bumped.
   * @param {object} data
   */
  function update(data) {
    const current = ProfileRepository.get() || makeProfile(resolveIdentity().id);
    const allowed = ['username', 'avatar_seed'];
    if (data && typeof data === 'object') {
      allowed.forEach(function (key) {
        if (data[key] !== undefined && typeof data[key] === 'string') {
          current[key] = data[key];
        }
      });
    }
    current.version = SCHEMA_VERSION;
    current.updated_at = now();
    ProfileRepository.save(current);
    notifySync();
    return current;
  }

  /** Delete the account profile. */
  function clear() {
    ProfileRepository.clear();
  }

  /** True if a valid profile linked to the current identity exists. */
  function exists() {
    const p = ProfileRepository.get();
    if (!p) return false;
    const identity = Identity.get();
    // If there is no identity, there cannot be a valid linked profile.
    return !!(identity && p.identity_id === identity.id);
  }

  window.UserProfile = {
    init: init,
    get: get,
    create: create,
    update: update,
    clear: clear,
    exists: exists
  };
})();
